import os as _os
_DEBUG_I18N = _os.environ.get("SERBABISA_DEBUG_I18N", "").lower() == "1"

def get_lang():
    try:
        from flask import request
        # First check cookie, then args, default to 'id'
        if request:
            lang = request.cookies.get('language')
            if not lang:
                lang = request.args.get('lang')
            if lang in ['id', 'en']:
                return lang
    except Exception:
        pass
    # fallback to config
    try:
        import json
        with open('config.json', 'r') as f:
            return json.load(f).get('language', 'id')
    except:
        return 'id'

def m(text, lang=None, **kwargs):
    if not text: return text
    if not lang:
        lang = get_lang()
    
    # Check UI_STRINGS first
    lang_dict = UI_STRINGS.get(lang, UI_STRINGS.get("id", {}))
    if text in lang_dict:
        result = lang_dict[text]
    else:
        # Check TOOL_TRANSLATIONS
        if lang == "en":
            result = TOOL_TRANSLATIONS.get(text, text)
        elif lang == "id":
            # Reverse lookup if needed
            result = text
            for k, v in TOOL_TRANSLATIONS.items():
                if v == text:
                    result = k
                    break
        else:
            result = text
            
    for k, v in kwargs.items():
        result = result.replace(f"{{{k}}}", str(v))
    return result

def translate_ui(key, lang="id", **kwargs):
    lang_dict = UI_STRINGS.get(lang, UI_STRINGS["id"])
    if key in lang_dict:
        text = lang_dict[key]
    else:
        fallback_lang = "en" if lang == "id" else "id"
        fallback_dict = UI_STRINGS.get(fallback_lang, {})
        if key in fallback_dict:
            text = fallback_dict[key]
        elif _DEBUG_I18N:
            text = f"[!{key}]"
        else:
            text = key
    for k, v in kwargs.items():
        text = text.replace(f"{{{k}}}", str(v))
    return text

